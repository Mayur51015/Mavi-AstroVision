// @desc    Get all published articles
// @route   GET /api/articles
// @access  Public
export const getArticles = async (req, res) => {
  try {
    const { category, search, tag, page = 1, limit = 9 } = req.query;

    // Check if auto-seed is needed
    const count = await Article.countDocuments();
    if (count === 0) {
      await Article.insertMany(SEED_ARTICLES);
    }

    const filter = { isPublished: true };
    if (category && category !== 'All') {
      filter.category = category;
    }
    if (tag) {
      filter.tags = tag;
    }
    if (search) {
      filter.$or = [
        { title: { $regex: search, $options: 'i' } },
        { excerpt: { $regex: search, $options: 'i' } },
        { tags: { $regex: search, $options: 'i' } },
      ];
    }

    const articles = await Article.find(filter)
      .sort({ featured: -1, createdAt: -1 })
      .skip((page - 1) * limit)
      .limit(Number(limit));

    const total = await Article.countDocuments(filter);

    res.json({
      success: true,
      articles,
      pagination: {
        currentPage: Number(page),
        totalPages: Math.ceil(total / limit) || 1,
        total,
      },
    });
  } catch (error) {
    console.error('getArticles error:', error);
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Get single article by slug
// @route   GET /api/articles/:slug
// @access  Public
export const getArticleBySlug = async (req, res) => {
  try {
    const { slug } = req.params;
    const article = await Article.findOneAndUpdate(
      { slug, isPublished: true },
      { $inc: { views: 1 } },
      { new: true }
    );

    if (!article) {
      return res.status(404).json({ success: false, message: 'Article not found' });
    }

    // Get related articles in same category
    const related = await Article.find({
      category: article.category,
      _id: { $ne: article._id },
      isPublished: true,
    })
      .limit(3)
      .select('title slug excerpt coverImage readTime category');

    res.json({
      success: true,
      article,
      related,
    });
  } catch (error) {
    console.error('getArticleBySlug error:', error);
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Create article (Admin)
// @route   POST /api/articles
// @access  Admin
export const createArticle = async (req, res) => {
  try {
    const { title, excerpt, content, category, tags, coverImage, featured, readTime } = req.body;

    const slug = title
      .toLowerCase()
      .replace(/[^\w ]+/g, '')
      .replace(/ +/g, '-');

    const article = await Article.create({
      title,
      slug,
      excerpt,
      content,
      category,
      tags: Array.isArray(tags) ? tags : tags?.split(',').map((t) => t.trim()),
      coverImage,
      featured: Boolean(featured),
      readTime: readTime || '5 min read',
    });

    res.status(201).json({ success: true, article });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Update article (Admin)
// @route   PUT /api/articles/:id
// @access  Admin
export const updateArticle = async (req, res) => {
  try {
    const { title, excerpt, content, category, tags, coverImage, featured, readTime, isPublished } = req.body;

    const updateData = {};
    if (title) {
      updateData.title = title;
      updateData.slug = title
        .toLowerCase()
        .replace(/[^\w ]+/g, '')
        .replace(/ +/g, '-');
    }
    if (excerpt !== undefined) updateData.excerpt = excerpt;
    if (content !== undefined) updateData.content = content;
    if (category !== undefined) updateData.category = category;
    if (tags !== undefined) {
      updateData.tags = Array.isArray(tags) ? tags : tags.split(',').map((t) => t.trim());
    }
    if (coverImage !== undefined) updateData.coverImage = coverImage;
    if (featured !== undefined) updateData.featured = Boolean(featured);
    if (readTime !== undefined) updateData.readTime = readTime;
    if (isPublished !== undefined) updateData.isPublished = Boolean(isPublished);

    const article = await Article.findByIdAndUpdate(req.params.id, updateData, {
      new: true,
      runValidators: true,
    });

    if (!article) {
      return res.status(404).json({ success: false, message: 'Article not found' });
    }

    res.json({ success: true, article });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Delete article (Admin)
// @route   DELETE /api/articles/:id
// @access  Admin
export const deleteArticle = async (req, res) => {
  try {
    const article = await Article.findByIdAndDelete(req.params.id);
    if (!article) {
      return res.status(404).json({ success: false, message: 'Article not found' });
    }
    res.json({ success: true, message: 'Article deleted successfully' });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};
